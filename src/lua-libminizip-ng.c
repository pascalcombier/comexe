/* Returns the handle or nil */
static int MZ_ZipFileCreate (lua_State *LuaState)
{
  mz_zip_file *FileInfo = calloc(1, sizeof(mz_zip_file));

  if (FileInfo == NULL)
  {
    lua_pushnil(LuaState);
  }
  else
  {
    lua_pushlightuserdata(LuaState, FileInfo);
  }

  return 1; /* Number of values returned on the stack */
}

static int MZ_ZipFileDelete (lua_State *LuaState)
{
  void *FileInfo = lua_touserdata(LuaState, 1);

  free(FileInfo);

  return 0; /* Number of values returned on the stack */
}

