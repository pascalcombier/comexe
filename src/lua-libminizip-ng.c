extern int luaopen_minizipng (lua_State *LuaState)
{
  /* Create the table with all functions */
  luaL_newlib(LuaState, MINIZIP_FUNCTIONS);

  /* Register constants */
  MZ_RegisterVersionConstants(LuaState);
  MZ_RegisterErrorConstants(LuaState);
  MZ_RegisterOpenModeConstants(LuaState);
  MZ_RegisterCompressionConstants(LuaState);
  MZ_RegisterZlibConstants(LuaState);
  MZ_RegisterFlagConstants(LuaState);
  MZ_RegisterHostSystemConstants(LuaState);

  return 1; /* Number of values returned on the stack */
}
