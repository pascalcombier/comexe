/* The returned handle stays valid until the entry cursor moves (goto_next_entry
 * or locate_entry).
 */
static int MZ_ZipEntryGetInfo (lua_State *LuaState)
{
  void        *ZipHandle = lua_touserdata(LuaState, 1);
  mz_zip_file *FileInfo  = NULL;
  int32_t      Result    = mz_zip_entry_get_info(ZipHandle, &FileInfo);

  if ((Result == MZ_OK) && (FileInfo != NULL))
  {
    lua_pushlightuserdata(LuaState, FileInfo);
    lua_pushnil(LuaState);
  }
  else
  {
    lua_pushnil(LuaState);
    lua_pushinteger(LuaState, Result);
  }

  return 2; /* Number of values returned on the stack */
}

