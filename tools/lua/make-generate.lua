local Runtime = require("com.runtime")
local Model   = require("make-model")

local format = string.format
local gsub   = string.gsub
local concat = table.concat
local append = table.insert
local stderr = io.stderr

local writefile   = Runtime.writefile
local newpathname = Runtime.newpathname

--------------------------------------------------------------------------------
-- PRIVATE FUNCTIONS                                                          --
--------------------------------------------------------------------------------

local function GEN_NativePathname (Model, InternalPathname)
  return gsub(InternalPathname, "/", Model.HostSeparator)
end

local function GEN_EmitHeader (Model, Lines)
  -- Retrieve data
  local Triples = Model.Triples
  -- Headers
  append(Lines, "# FILE GENERATED BY make-generate.lua")
  append(Lines, format("# Source %s", Model.RootFile))
  append(Lines, format("#   Host %s", Model.HostOS))
  for Index = 1, #Triples do
    append(Lines, format("# Triple %s", Triples[Index]))
  end
  append(Lines, "")
  -- Collect environment names for EXPORT
  local Names = {}
  for Name in pairs(Model.Environment) do
    append(Names, Name)
  end
  table.sort(Names)
  -- Generate the exports
  for Index, Name in ipairs(Names) do
    local ExportLine = format("export %s = %s", Name, Model.Environment[Name])
    append(Lines, ExportLine)
  end
  -- Add a blank line after the exports
  if (#Names > 0) then
    append(Lines, "")
  end
end

local function GEN_EmitDirMarkerRule (Model, Lines)
  append(Lines, format("%s%s%s:", "%", Model.HostSeparator, Model.MarkerName))
  if (Model.HostOS == "windows") then
    append(Lines, "\tif not exist $* mkdir $*")
    append(Lines, "\ttype NUL > $@")
  else
    append(Lines, "\tmkdir -p $*")
    append(Lines, "\ttouch $@")
  end
  append(Lines, "")
end

local function GEN_Prerequisites (Model, Rule)
  -- Retrieve data
  local Prerequisites = Rule.Prerequisites
  local Items         = {}
  -- Convert each prerequisite to HOST separator \ or /
  for Index, Prerequisite in ipairs(Prerequisites) do
    local NativePrerequisite = GEN_NativePathname(Model, Prerequisite)
    append(Items, NativePrerequisite)
  end
  -- Adds "dir/auto-dir-ok" as last prerequisite for auto directory creation
  local OutputDir = Rule.OutDir
  if (OutputDir ~= "") then
    local NativeOutputDir    = GEN_NativePathname(Model, OutputDir)
    local MarkerPrerequisite = format("%s%s%s", NativeOutputDir, Model.HostSeparator, Model.MarkerName)
    append(Items, MarkerPrerequisite)
  end
  -- Merge into a single string
  local PrerequisitesString = concat(Items, " ")
  return PrerequisitesString
end

local function GEN_EmitRule (Model, Lines, Rule)
  -- Prepare
  local MainOut       = Rule.Outs[1]
  local TargetName    = GEN_NativePathname(Model, MainOut)
  local LeftPart      = format("%s:", TargetName)
  local Prerequisites = GEN_Prerequisites(Model, Rule)
  local RuleLine
  if (Prerequisites == "") then
    RuleLine = format("%s:", TargetName)
  else
    RuleLine = format("%s: %s", TargetName, Prerequisites)
  end
  -- Add the lines
  append(Lines, RuleLine)
  for Index, RunLine in ipairs(Rule.RunLines) do
    local IndentedLine = format("\t%s", RunLine)
    append(Lines, IndentedLine)
  end
end

--------------------------------------------------------------------------------
-- PUBLIC FUNCTIONS                                                           --
--------------------------------------------------------------------------------

local function GEN_Generate (Model)
  -- local data
  local Lines = {}
  -- Header
  GEN_EmitHeader(Model, Lines)
  append(Lines, ".PHONY: clean all")
  append(Lines, "")
  -- First target is "all"
  local AllNames = {}
  for Index, Artifact in ipairs(Model.Artifacts) do
    local NativeArtifact = GEN_NativePathname(Model, Artifact)
    append(AllNames, NativeArtifact)
  end
  append(Lines, format("all: %s", concat(AllNames, " ")))
  append(Lines, "")
  -- Directory Marker rule
  GEN_EmitDirMarkerRule(Model, Lines)
  -- All the rules
  for Index, Rule in ipairs(Model.Rules) do
    GEN_EmitRule(Model, Lines, Rule)
    append(Lines, "")
  end
  -- Clean rule
  append(Lines, "clean:")
  for Index, CleanCommand in ipairs(Model.CleanCommands) do
    append(Lines, format("\t%s", CleanCommand))
  end
  return concat(Lines, "\n")
end

