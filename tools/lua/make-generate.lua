local USAGE = [[usage: lua55ce tools/lua/make-generate.lua <root-description> [options]
options:
  --output <name>       Output filename (optional)
  --host <arch-os-libc> Target host (optional, default: current host)

examples: --host x86_64-linux-musl
]]

local EXIT_SUCCESS = 0
local EXIT_ERROR   = 1

local function GEN_Usage ()
  stderr:write(USAGE)
  os.exit(EXIT_ERROR)
end

local function GEN_FatalError (ErrorString)
  stderr:write(format("%s\n",ErrorString))
  GEN_Usage()
end

local function GEN_ParseArguments (Arguments)
  local NewOptions = {
    Output   = false,
    Host     = false,
    RootFile = false,
  }
  local Index = 1
  while (Index <= #Arguments) do
    local Entry = Arguments[Index]
    if (Entry == "--output") then
      Index = (Index + 1)
      NewOptions.Output = Arguments[Index]
      assert(NewOptions.Output, "--output requires a filename")
    elseif (Entry == "--host") then
      Index = (Index + 1)
      local HostTriple = Arguments[Index]
      assert(HostTriple, "--host requires a target triple (like x86_64-linux-musl)")
      NewOptions.Host = HostTriple
    elseif (not NewOptions.RootFile) then
      NewOptions.RootFile = Entry
    end
    Index = (Index + 1)
  end
  return NewOptions
end

--------------------------------------------------------------------------------
-- MAIN                                                                       --
--------------------------------------------------------------------------------

local Options = GEN_ParseArguments(arg)

if (not Options.RootFile) then
  GEN_FatalError()
end

local MakeModel  = Model.Build(Options.RootFile, Options.Host)
local OutputName = Options.Output

-- No flag "--output" was given, choose a default name
if (not OutputName) then
  local BaseName = gsub(Options.RootFile, "%.lua$", "")
  OutputName = format("%s-makefile-%s", BaseName, MakeModel.HostTriple)
end

local OutputDir = newpathname(OutputName):getdirectory("native")

if (OutputDir ~= "") then
  Runtime.makedirectory(OutputDir)
end

local MakefileContents = GEN_Generate(MakeModel)

local Success, ErrorString = writefile(OutputName, MakefileContents)
if (not Success) then
  error(format("cannot write %s: %s", OutputName, ErrorString))
end

os.exit(EXIT_SUCCESS)
